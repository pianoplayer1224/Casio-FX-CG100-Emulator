#!/usr/bin/env python3
"""Generate the casioplot font header (micropython/ports/cg100/cgfont.h).

Glyphs and advances come from the calculator itself: calc/cgglyph.py reads
each glyph back with get_pixel, shows it magnified and prints its advance;
tools/glyphdecode.py turned the photos into cgfont_calc.json. A character
missing from the json falls back to a DejaVu placeholder in the same cell,
with large fixed at 18 px and small/medium spaced by ink width plus a gap.
"""
import json
import os
import sys

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "micropython", "ports", "cg100", "cgfont.h")
CALC = os.path.join(HERE, "cgfont_calc.json")
SANS = "/usr/share/fonts/TTF/DejaVuSans.ttf"
MONO = "/usr/share/fonts/TTF/DejaVuSansMono.ttf"
# name: (placeholder font, cell width, cell height, fixed advance or 0,
#        provisional gap after the ink)
SIZES = {"small": (SANS, 8, 10, 0, 0.56), "medium": (SANS, 15, 17, 0, 1.56),
         "large": (MONO, 18, 23, 18, 0), "shell": (MONO, 10, 18, 10, 0)}
FIRST, LAST = 32, 126


def placeholder(path, gw, gh):
    """DejaVu glyphs fitted to the cell: {code: rows}, ink starting at x=1."""
    for px in range(40, 4, -1):
        font = ImageFont.truetype(path, px)
        a, d = font.getmetrics()
        wide = max(font.getbbox(chr(c))[2] for c in range(FIRST, LAST + 1))
        if a + d <= gh + 1 and wide <= gw:
            break
    cut = 80 if gh < 12 else 128
    out = {}
    for c in range(FIRST, LAST + 1):
        img = Image.new("L", (gw, gh), 0)
        ImageDraw.Draw(img).text((1, 0), chr(c), fill=255, font=font)
        out[c] = ["".join("#" if img.getpixel((x, y)) >= cut else "." for x in range(gw))
                  for y in range(gh)]
    return out


def main():
    for f in (SANS, MONO):
        if not os.path.exists(f):
            sys.exit("font not found: " + f)
    calc = json.load(open(CALC))
    out = ["// Generated by emu/mkfont.py from emu/cgfont_calc.json (the calculator's",
           "// glyphs); DejaVu placeholders where listed below.",
           "#define CGFONT_FIRST %d" % FIRST, "#define CGFONT_LAST %d" % LAST, ""]
    for name, (path, gw, gh, fixed, gap) in SIZES.items():
        got = calc["sizes"].get(name, {})
        left, top = calc.get("offsets", {}).get(name, (calc["left"], calc["top"]))
        ph = placeholder(path, gw, gh)
        rows, adv, missing = [], [], []
        carry = 0.0
        for c in range(FIRST, LAST + 1):
            g = got.get(str(c))
            if g:
                cell = [["."] * gw for _ in range(gh)]
                for j, row in enumerate(g["rows"]):
                    for i, ch in enumerate(row):
                        if ch == "#" and 0 <= top + j < gh and 0 <= left + i < gw:
                            cell[top + j][left + i] = "#"
                bitmap = ["".join(r) for r in cell]
            else:
                bitmap = ph[c]
                missing.append(chr(c))
            for r in bitmap:
                rows.append(sum(1 << x for x, ch in enumerate(r) if ch == "#"))
            if g and "adv" in g:
                a = g["adv"]
            elif fixed:
                a = fixed
            else:
                ink = [x for r in bitmap for x, ch in enumerate(r) if ch == "#"]
                carry += (max(ink) + 1 if ink else 2) + gap
                a = int(carry); carry -= a
            adv.append(a)
        out.append("// %s: placeholders for %s" % (name, "".join(missing) or "none"))
        out.append("static const uint32_t cgfont_%s[%d] = {" % (name, len(rows)))
        for i in range(0, len(rows), gh):
            out.append("    " + ",".join("0x%x" % r for r in rows[i:i + gh]) + ",")
        out.append("};")
        out.append("static const uint8_t cgfont_%s_adv[%d] = {%s};" %
                   (name, len(adv), ",".join(map(str, adv))))
        out.append("#define CGFONT_%s_W %d" % (name.upper(), gw))
        out.append("#define CGFONT_%s_H %d" % (name.upper(), gh))
        out.append("")
    open(OUT, "w").write("\n".join(out))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
